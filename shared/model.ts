/**
 * Poll set model shared by the Convex backend, the NestJS worker and the
 * browser editor. Plain data only: no runtime imports, so every bundle can
 * pull it in.
 */

export const FIELD_TYPES = [
  'text',
  'textarea',
  'email',
  'tel',
  'number',
  'date',
  'select',
  'checkbox',
] as const;
export type FieldType = (typeof FIELD_TYPES)[number];

/** Human names for the editor's type picker. */
export const FIELD_TYPE_NAMES: Record<FieldType, string> = {
  text: 'Short text',
  textarea: 'Paragraph',
  email: 'Email',
  tel: 'Phone',
  number: 'Number',
  date: 'Date',
  select: 'Dropdown',
  checkbox: 'Checkbox',
};

export const QUESTION_TYPES = ['single', 'multiple', 'rating', 'text'] as const;
export type QuestionType = (typeof QUESTION_TYPES)[number];

export const QUESTION_TYPE_NAMES: Record<QuestionType, string> = {
  single: 'One choice',
  multiple: 'Several choices',
  rating: 'Rating 1–5',
  text: 'Written answer',
};

export const SET_STATUSES = ['draft', 'published', 'closed'] as const;
export type SetStatus = (typeof SET_STATUSES)[number];

export interface ProfileField {
  id: string;
  label: string;
  type: FieldType;
  required: boolean;
  /** Choices for `select`; empty for every other type. */
  options: string[];
  /**
   * Each value may be used by one respondent only (e.g. one response per
   * email). Optional so sets saved before this existed still load.
   */
  unique?: boolean;
}

/** Field types whose values can identify a person, so can be kept unique. */
export const UNIQUE_FIELD_TYPES: readonly FieldType[] = [
  'text',
  'email',
  'tel',
  'number',
];

export interface Choice {
  id: string;
  label: string;
}

export interface Question {
  id: string;
  prompt: string;
  type: QuestionType;
  required: boolean;
  /** Choices for `single` and `multiple`; empty for `rating` and `text`. */
  options: Choice[];
}

export interface SetContent {
  title: string;
  description: string;
  fields: ProfileField[];
  questions: Question[];
}

/** One respondent's answer to one question. */
export interface Answer {
  questionId: string;
  /** Picked choice ids; for `rating` the single value "1".."5". */
  optionIds: string[];
  /** Written answer for `text` questions, otherwise empty. */
  text: string;
}

export const RATING_VALUES = ['1', '2', '3', '4', '5'] as const;

export const LIMITS = {
  title: 120,
  description: 600,
  label: 200,
  choice: 120,
  fields: 20,
  questions: 50,
  choices: 20,
  fieldValue: 500,
  textAnswer: 1000,
} as const;

/** Public link code: 10 characters, no look-alikes (0/o, 1/l/i). */
export const SLUG_ALPHABET = 'abcdefghjkmnpqrstuvwxyz23456789';
export const SLUG_LENGTH = 10;
export const SLUG_PATTERN = /^[a-hjkmnp-z2-9]{10}$/;

/** Ids for fields, questions and choices, generated by the editor. */
export const ITEM_ID_PATTERN = /^[a-z0-9]{1,24}$/;
