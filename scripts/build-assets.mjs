// Builds browser assets into public/: Tailwind CSS and client scripts with
// content-hashed names (cached as immutable), plus self-hosted fonts. Writes
// src/generated/assets.ts so the worker links the current hashes.
// `--watch` rebuilds on change for `pnpm dev`.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { watch } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'public', 'assets');
const fonts = join(root, 'public', 'fonts');
const manifestPath = join(root, 'src', 'generated', 'assets.ts');

// Geist, Geist Mono, Archivo and Impacted are committed in public/fonts,
// already subset to Latin (Impacted to the letters of POLLER): the full
// Geist files are twice the size for scripts the UI never sets.
const FONT_SOURCES = {
  'instrument-serif-italic.woff2':
    'node_modules/@fontsource/instrument-serif/files/instrument-serif-latin-400-italic.woff2',
};

const SCRIPTS = {
  boot: 'client/boot.ts',
  app: 'client/app.ts',
  editor: 'client/editor.ts',
};

const hash = buffer =>
  createHash('sha256').update(buffer).digest('base64url').slice(0, 10);

async function emit(name, ext, contents) {
  const file = `${name}.${hash(contents)}.${ext}`;
  await writeFile(join(out, file), contents);
  return `/assets/${file}`;
}

async function buildCss() {
  const tmp = join(root, 'node_modules', '.cache', 'poller-app.css');
  await mkdir(dirname(tmp), { recursive: true });
  const bin = join(
    root,
    'node_modules',
    '@tailwindcss',
    'cli',
    'dist',
    'index.mjs'
  );
  execFileSync(
    process.execPath,
    [bin, '-i', 'styles/app.css', '-o', tmp, '--minify'],
    {
      cwd: root,
      stdio: ['ignore', 'ignore', 'inherit'],
    }
  );
  return emit('app', 'css', await readFile(tmp));
}

async function buildScripts() {
  const result = await esbuild.build({
    entryPoints: SCRIPTS,
    bundle: true,
    minify: true,
    format: 'esm',
    target: ['chrome120', 'firefox120', 'safari17'],
    write: false,
    outdir: 'out',
    legalComments: 'none',
    absWorkingDir: root,
  });
  const paths = {};
  for (const file of result.outputFiles) {
    const name = file.path.split(/[\\/]/).pop().replace(/\.js$/, '');
    paths[name] = await emit(name, 'js', file.contents);
  }
  return paths;
}

async function copyFonts() {
  await mkdir(fonts, { recursive: true });
  await Promise.all(
    Object.entries(FONT_SOURCES).map(([to, from]) =>
      copyFile(join(root, from), join(fonts, to))
    )
  );
}

async function build() {
  await rm(out, { recursive: true, force: true });
  await mkdir(out, { recursive: true });
  const [css, scripts] = await Promise.all([
    buildCss(),
    buildScripts(),
    copyFonts(),
  ]);
  const manifest = { css, ...scripts };
  await mkdir(dirname(manifestPath), { recursive: true });
  const body = `// Generated by scripts/build-assets.mjs. Do not edit.\nexport const ASSETS = ${JSON.stringify(manifest, null, 2)} as const;\n`;
  const previous = await readFile(manifestPath, 'utf8').catch(() => '');
  if (previous !== body) await writeFile(manifestPath, body);
  console.log(`assets: ${Object.values(manifest).join(', ')}`);
}

await build();

if (process.argv.includes('--watch')) {
  let timer;
  const rebuild = () => {
    clearTimeout(timer);
    timer = setTimeout(
      () => build().catch(error => console.error(error.message)),
      120
    );
  };
  for (const dir of ['client', 'styles', 'shared', 'src/views', 'src/pages']) {
    watch(join(root, dir), { recursive: true }, rebuild);
  }
  console.log('assets: watching for changes');
}
